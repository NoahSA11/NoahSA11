/**
 * Writes dist/sw.js: precaches the app shell immediately and every content file
 * (all five books) in the background, so the app works fully offline after the
 * first visit. Cache name is a hash of the file list + sizes.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const DIST = join(import.meta.dirname, '..', 'dist');
const walk = (d: string): string[] => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const files = walk(DIST).map((f) => relative(DIST, f).split('\\').join('/')).filter((f) => f !== 'sw.js').sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);
const shell = ['./', ...files.filter((f) => !f.startsWith('content/') || f === 'content/index.json' || f === 'content/calendar.json').map((f) => './' + f)];
const content = files.filter((f) => f.startsWith('content/') && !shell.includes('./' + f)).map((f) => './' + f);
const total = files.reduce((s, f) => s + statSync(join(DIST, f)).size, 0);

const sw = `/* Shvil service worker — generated by scripts/build-sw.ts */
const CACHE = 'shvil-${version}';
const SHELL = ${JSON.stringify(shell)};
const CONTENT = ${JSON.stringify(content)};
self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const c = await caches.open(CACHE);
    await c.addAll(SHELL);
    // Book data: fetched in the background so the first load stays light.
    c.addAll(CONTENT).catch(() => {});
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith((async () => {
    const c = await caches.open(CACHE);
    const hit = await c.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try {
      const res = await fetch(req);
      if (res.ok) c.put(req, res.clone());
      return res;
    } catch (err) {
      if (req.mode === 'navigate') return (await c.match('./')) || Response.error();
      throw err;
    }
  })());
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`sw.js: cache ${version}, ${shell.length} shell + ${content.length} content files, dist total ${(total / 1024 / 1024).toFixed(2)} MB`);
